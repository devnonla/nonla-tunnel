//! Nonla Tunnel Protocol — Message definitions and async reader/writer.
//!
//! Binary frame format:
//! ```text
//! ┌──────────┬──────────┬───────────┬──────────────────┐
//! │ Version  │  Type    │  Length   │     Payload      │
//! │ (1 byte) │ (1 byte) │ (4 bytes) │  (N bytes)       │
//! └──────────┴──────────┴───────────┴──────────────────┘
//! ```

use anyhow::{bail, Context, Result};
use bytes::{Buf, BufMut, BytesMut};
use serde::{Deserialize, Serialize};
use tokio::io::{AsyncRead, AsyncReadExt, AsyncWrite, AsyncWriteExt};

/// Protocol version
pub const PROTOCOL_VERSION: u8 = 1;

/// Maximum payload size (16 MB)
pub const MAX_PAYLOAD_SIZE: u32 = 16 * 1024 * 1024;

/// Maximum payload accepted before a client has authenticated.
/// An `AuthReq` is a few hundred bytes; this stops pre-auth memory abuse.
pub const MAX_AUTH_PAYLOAD_SIZE: u32 = 4 * 1024;

/// Maximum tunnel name length (one DNS label).
pub const MAX_CLIENT_ID_LEN: usize = 63;

/// Validate a tunnel name: one lowercase DNS label, `[a-z0-9-]`, 1–63 chars,
/// no leading/trailing `-`. The name ends up in a public hostname and in
/// Traefik YAML, so nothing else is accepted.
pub fn validate_client_id(id: &str) -> std::result::Result<(), String> {
    if id.is_empty() || id.len() > MAX_CLIENT_ID_LEN {
        return Err(format!(
            "tunnel name must be 1-{} characters",
            MAX_CLIENT_ID_LEN
        ));
    }
    if !id
        .bytes()
        .all(|b| b.is_ascii_lowercase() || b.is_ascii_digit() || b == b'-')
    {
        return Err("tunnel name may only contain a-z, 0-9 and '-'".into());
    }
    if id.starts_with('-') || id.ends_with('-') {
        return Err("tunnel name must not start or end with '-'".into());
    }
    Ok(())
}

/// Hex-encoded SHA-256.
pub fn sha256_hex(data: &[u8]) -> String {
    use sha2::Digest;
    sha2::Sha256::digest(data)
        .iter()
        .map(|b| format!("{:02x}", b))
        .collect()
}

/// Default control port
pub const DEFAULT_CONTROL_PORT: u16 = 6200;

/// Default public port (HTTP subdomain routing + install endpoint)
pub const DEFAULT_PUBLIC_PORT: u16 = 6210;

/// Heartbeat interval in seconds
pub const HEARTBEAT_INTERVAL_SECS: u64 = 15;

/// Heartbeat timeout in seconds (5 missed heartbeats)
pub const HEARTBEAT_TIMEOUT_SECS: u64 = 90;

/// Consecutive missed heartbeats before a reconnect may take over the session.
/// One miss is treated as jitter (the driver already waits 10s per probe);
/// two misses (~40s) is a zombie, well before the 5-miss hard disconnect.
pub const TAKEOVER_AFTER_MISSED_HEARTBEATS: u32 = 2;

/// Wall-clock fallback if the driver stops updating miss counts (or the client
/// has no heartbeat). Matches the 5-miss disconnect budget.
pub const SESSION_STALE_SECS: u64 = HEARTBEAT_TIMEOUT_SECS;

/// Stream type markers for yamux streams
pub const STREAM_TYPE_PROXY: u8 = 0x00;
pub const STREAM_TYPE_HEARTBEAT: u8 = 0x01;

// ─── Message Types ───────────────────────────────────────────────

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum MessageType {
    AuthReq = 0x01,
    AuthRes = 0x02,
    NewConn = 0x03,
    Data = 0x04,
    Ping = 0x05,
    Pong = 0x06,
    Close = 0x07,
    Error = 0x08,
    AcceptConn = 0x09,
    EnrollReq = 0x0A,
    EnrollRes = 0x0B,
}

impl TryFrom<u8> for MessageType {
    type Error = anyhow::Error;

    fn try_from(value: u8) -> Result<Self> {
        match value {
            0x01 => Ok(Self::AuthReq),
            0x02 => Ok(Self::AuthRes),
            0x03 => Ok(Self::NewConn),
            0x04 => Ok(Self::Data),
            0x05 => Ok(Self::Ping),
            0x06 => Ok(Self::Pong),
            0x07 => Ok(Self::Close),
            0x08 => Ok(Self::Error),
            0x09 => Ok(Self::AcceptConn),
            0x0A => Ok(Self::EnrollReq),
            0x0B => Ok(Self::EnrollRes),
            _ => bail!("Unknown message type: 0x{:02x}", value),
        }
    }
}

// ─── Message Payloads ────────────────────────────────────────────

/// Authentication request from client
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AuthReq {
    pub client_id: String,
    pub token: String,
    #[serde(default)]
    pub version: Option<String>,
    /// Per-name secret generated by the client. The first session to use a
    /// name with a key owns it; later sessions need the same key.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub claim_key: Option<String>,
}

impl AuthReq {
    /// Whether the client sends heartbeats and stream type markers
    /// (every nonla-tunnel client does; kept for protocol robustness).
    pub fn supports_heartbeat(&self) -> bool {
        self.version.is_some()
    }
}

/// Authentication response from server
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AuthRes {
    pub success: bool,
    pub message: String,
    /// The public HTTP port
    pub public_port: Option<u16>,
    /// Assigned subdomain route (e.g. "my-app")
    pub assigned_route: Option<String>,
}

/// Prefix of one-time enrollment invites (`nti_…`).
pub const INVITE_PREFIX: &str = "nti_";
/// Prefix of per-client credentials issued at enrollment (`ntc_…`).
pub const CREDENTIAL_PREFIX: &str = "ntc_";

/// Enrollment: trade a one-time invite for a per-client credential.
/// Sent instead of `AuthReq` as the first message; the server closes the
/// connection after answering.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EnrollReq {
    pub invite: String,
    /// Free-form client description (e.g. hostname), for `clients` listings.
    #[serde(default)]
    pub label: Option<String>,
}

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct EnrollRes {
    pub success: bool,
    pub message: String,
    /// The permanent credential — the client stores this, not the invite.
    #[serde(default)]
    pub token: Option<String>,
    /// Credential id (for `nonla-tunnel-server revoke <id>`).
    #[serde(default)]
    pub client_ref: Option<String>,
}

/// Server notifying client of a new incoming connection
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct NewConn {
    pub conn_id: uuid::Uuid,
}

/// Client accepting a connection (sent on a new TCP stream)
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct AcceptConn {
    pub conn_id: uuid::Uuid,
    pub client_id: String,
}

// ─── Unified Message Enum ────────────────────────────────────────

#[derive(Debug, Clone)]
pub enum Message {
    AuthReq(AuthReq),
    AuthRes(AuthRes),
    NewConn(NewConn),
    AcceptConn(AcceptConn),
    EnrollReq(EnrollReq),
    EnrollRes(EnrollRes),
    Ping,
    Pong,
    Close,
    Error(String),
}

impl Message {
    /// Get the message type byte
    fn msg_type(&self) -> MessageType {
        match self {
            Message::AuthReq(_) => MessageType::AuthReq,
            Message::AuthRes(_) => MessageType::AuthRes,
            Message::NewConn(_) => MessageType::NewConn,
            Message::AcceptConn(_) => MessageType::AcceptConn,
            Message::EnrollReq(_) => MessageType::EnrollReq,
            Message::EnrollRes(_) => MessageType::EnrollRes,
            Message::Ping => MessageType::Ping,
            Message::Pong => MessageType::Pong,
            Message::Close => MessageType::Close,
            Message::Error(_) => MessageType::Error,
        }
    }

    /// Serialize the payload to bytes
    fn encode_payload(&self) -> Result<Vec<u8>> {
        match self {
            Message::AuthReq(p) => serde_json::to_vec(p).context("encode AuthReq"),
            Message::AuthRes(p) => serde_json::to_vec(p).context("encode AuthRes"),
            Message::NewConn(p) => serde_json::to_vec(p).context("encode NewConn"),
            Message::AcceptConn(p) => serde_json::to_vec(p).context("encode AcceptConn"),
            Message::EnrollReq(p) => serde_json::to_vec(p).context("encode EnrollReq"),
            Message::EnrollRes(p) => serde_json::to_vec(p).context("encode EnrollRes"),
            Message::Error(msg) => Ok(msg.as_bytes().to_vec()),
            Message::Ping | Message::Pong | Message::Close => Ok(vec![]),
        }
    }

    /// Deserialize from type + payload bytes
    fn decode(msg_type: MessageType, payload: &[u8]) -> Result<Self> {
        match msg_type {
            MessageType::AuthReq => {
                let p: AuthReq = serde_json::from_slice(payload).context("decode AuthReq")?;
                Ok(Message::AuthReq(p))
            }
            MessageType::AuthRes => {
                let p: AuthRes = serde_json::from_slice(payload).context("decode AuthRes")?;
                Ok(Message::AuthRes(p))
            }
            MessageType::NewConn => {
                let p: NewConn = serde_json::from_slice(payload).context("decode NewConn")?;
                Ok(Message::NewConn(p))
            }
            MessageType::AcceptConn => {
                let p: AcceptConn = serde_json::from_slice(payload).context("decode AcceptConn")?;
                Ok(Message::AcceptConn(p))
            }
            MessageType::EnrollReq => {
                let p: EnrollReq = serde_json::from_slice(payload).context("decode EnrollReq")?;
                Ok(Message::EnrollReq(p))
            }
            MessageType::EnrollRes => {
                let p: EnrollRes = serde_json::from_slice(payload).context("decode EnrollRes")?;
                Ok(Message::EnrollRes(p))
            }
            MessageType::Error => {
                let msg = String::from_utf8_lossy(payload).to_string();
                Ok(Message::Error(msg))
            }
            MessageType::Ping => Ok(Message::Ping),
            MessageType::Pong => Ok(Message::Pong),
            MessageType::Close => Ok(Message::Close),
            MessageType::Data => bail!("DATA messages should not go through Message::decode"),
        }
    }
}

// ─── Async Writer ────────────────────────────────────────────────

/// Write a protocol message to an async writer
pub async fn write_message<W: AsyncWrite + Unpin>(writer: &mut W, msg: &Message) -> Result<()> {
    let payload = msg.encode_payload()?;
    let payload_len = payload.len() as u32;

    if payload_len > MAX_PAYLOAD_SIZE {
        bail!(
            "Payload too large: {} bytes (max {})",
            payload_len,
            MAX_PAYLOAD_SIZE
        );
    }

    let mut buf = BytesMut::with_capacity(6 + payload.len());
    buf.put_u8(PROTOCOL_VERSION);
    buf.put_u8(msg.msg_type() as u8);
    buf.put_u32(payload_len);
    buf.put_slice(&payload);

    writer.write_all(&buf).await.context("write message")?;
    writer.flush().await.context("flush message")?;
    Ok(())
}

/// Read a protocol message from an async reader
pub async fn read_message<R: AsyncRead + Unpin>(reader: &mut R) -> Result<Message> {
    read_message_max(reader, MAX_PAYLOAD_SIZE).await
}

/// Read a protocol message, rejecting payloads larger than `max_payload`
/// before allocating.
pub async fn read_message_max<R: AsyncRead + Unpin>(
    reader: &mut R,
    max_payload: u32,
) -> Result<Message> {
    // Read header: version (1) + type (1) + length (4) = 6 bytes
    let mut header = [0u8; 6];
    reader
        .read_exact(&mut header)
        .await
        .context("read message header")?;

    let mut buf = &header[..];
    let version = buf.get_u8();
    let msg_type_byte = buf.get_u8();
    let payload_len = buf.get_u32();

    if version != PROTOCOL_VERSION {
        bail!(
            "Protocol version mismatch: got {}, expected {}",
            version,
            PROTOCOL_VERSION
        );
    }

    let msg_type = MessageType::try_from(msg_type_byte)?;

    if payload_len > max_payload.min(MAX_PAYLOAD_SIZE) {
        bail!(
            "Payload too large: {} bytes (max {})",
            payload_len,
            max_payload.min(MAX_PAYLOAD_SIZE)
        );
    }

    // Read payload
    let mut payload = vec![0u8; payload_len as usize];
    if payload_len > 0 {
        reader
            .read_exact(&mut payload)
            .await
            .context("read message payload")?;
    }

    Message::decode(msg_type, &payload)
}

#[cfg(test)]
mod tests {
    use super::*;
    use tokio::io::duplex;

    #[tokio::test]
    async fn test_roundtrip_auth_req() {
        let (mut client, mut server) = duplex(1024);

        let msg = Message::AuthReq(AuthReq {
            client_id: "test-client".into(),
            token: "secret123".into(),
            version: None,
            claim_key: None,
        });

        write_message(&mut client, &msg).await.unwrap();
        let received = read_message(&mut server).await.unwrap();

        if let Message::AuthReq(auth) = received {
            assert_eq!(auth.client_id, "test-client");
            assert_eq!(auth.token, "secret123");
        } else {
            panic!("Expected AuthReq, got {:?}", received);
        }
    }

    #[tokio::test]
    async fn test_roundtrip_auth_res() {
        let (mut client, mut server) = duplex(1024);

        let msg = Message::AuthRes(AuthRes {
            success: true,
            message: "OK".into(),
            public_port: Some(6210),
            assigned_route: Some("my-app".into()),
        });

        write_message(&mut client, &msg).await.unwrap();
        let received = read_message(&mut server).await.unwrap();

        if let Message::AuthRes(res) = received {
            assert!(res.success);
            assert_eq!(res.assigned_route, Some("my-app".into()));
        } else {
            panic!("Expected AuthRes, got {:?}", received);
        }
    }

    #[tokio::test]
    async fn test_roundtrip_ping_pong() {
        let (mut client, mut server) = duplex(1024);

        write_message(&mut client, &Message::Ping).await.unwrap();
        let received = read_message(&mut server).await.unwrap();
        assert!(matches!(received, Message::Ping));

        write_message(&mut server, &Message::Pong).await.unwrap();
        let received = read_message(&mut client).await.unwrap();
        assert!(matches!(received, Message::Pong));
    }

    #[tokio::test]
    async fn test_roundtrip_new_conn() {
        let (mut client, mut server) = duplex(1024);

        let conn_id = uuid::Uuid::new_v4();
        let msg = Message::NewConn(NewConn { conn_id });

        write_message(&mut server, &msg).await.unwrap();
        let received = read_message(&mut client).await.unwrap();

        if let Message::NewConn(nc) = received {
            assert_eq!(nc.conn_id, conn_id);
        } else {
            panic!("Expected NewConn, got {:?}", received);
        }
    }

    #[tokio::test]
    async fn test_auth_res_with_none_fields() {
        let (mut client, mut server) = duplex(1024);

        let msg = Message::AuthRes(AuthRes {
            success: false,
            message: "denied".into(),
            public_port: None,
            assigned_route: None,
        });

        write_message(&mut client, &msg).await.unwrap();
        let received = read_message(&mut server).await.unwrap();

        if let Message::AuthRes(res) = received {
            assert!(!res.success);
            assert_eq!(res.message, "denied");
            assert!(res.public_port.is_none());
            assert!(res.assigned_route.is_none());
        } else {
            panic!("Expected AuthRes, got {:?}", received);
        }
    }

    #[tokio::test]
    async fn test_read_from_closed_connection() {
        let (client, mut server) = duplex(1024);
        drop(client); // close the writing end

        let result = read_message(&mut server).await;
        assert!(result.is_err());
    }

    #[tokio::test]
    async fn test_large_client_id() {
        let (mut client, mut server) = duplex(64 * 1024);

        let long_id = "a".repeat(1000);
        let msg = Message::AuthReq(AuthReq {
            client_id: long_id.clone(),
            token: "t".into(),
            version: None,
            claim_key: None,
        });

        write_message(&mut client, &msg).await.unwrap();
        let received = read_message(&mut server).await.unwrap();

        if let Message::AuthReq(auth) = received {
            assert_eq!(auth.client_id, long_id);
        } else {
            panic!("Expected AuthReq");
        }
    }

    #[tokio::test]
    async fn test_roundtrip_enroll() {
        let (mut a, mut b) = duplex(4096);
        write_message(
            &mut a,
            &Message::EnrollReq(EnrollReq {
                invite: "nti_abc".into(),
                label: Some("host".into()),
            }),
        )
        .await
        .unwrap();
        match read_message(&mut b).await.unwrap() {
            Message::EnrollReq(e) => assert_eq!(e.invite, "nti_abc"),
            other => panic!("{other:?}"),
        }
        write_message(
            &mut b,
            &Message::EnrollRes(EnrollRes {
                success: true,
                message: "ok".into(),
                token: Some("ntc_x".into()),
                client_ref: Some("c_1".into()),
            }),
        )
        .await
        .unwrap();
        match read_message(&mut a).await.unwrap() {
            Message::EnrollRes(r) => assert_eq!(r.token.as_deref(), Some("ntc_x")),
            other => panic!("{other:?}"),
        }
    }

    #[test]
    fn test_validate_client_id() {
        for ok in ["a", "my-api", "tunnel-1a2b3c4d", &"a".repeat(63)] {
            assert!(validate_client_id(ok).is_ok(), "{ok}");
        }
        for bad in [
            "",
            "-a",
            "a-",
            "My-Api",
            "a.b",
            "a_b",
            "a b",
            "x`) || HostRegexp(`.+",
            "x\"\n  hijack:",
            "../etc",
            &"a".repeat(64),
        ] {
            assert!(validate_client_id(bad).is_err(), "{bad:?}");
        }
    }

    #[tokio::test]
    async fn test_read_message_max_rejects_before_alloc() {
        let (mut client, mut server) = duplex(1024);
        // Header claiming a 1 MB AuthReq, no body sent.
        let mut hdr = vec![PROTOCOL_VERSION, MessageType::AuthReq as u8];
        hdr.extend_from_slice(&(1024u32 * 1024).to_be_bytes());
        tokio::io::AsyncWriteExt::write_all(&mut client, &hdr)
            .await
            .unwrap();
        let err = read_message_max(&mut server, MAX_AUTH_PAYLOAD_SIZE)
            .await
            .unwrap_err();
        assert!(err.to_string().contains("too large"));
    }

    #[test]
    fn test_sha256_hex() {
        assert_eq!(
            sha256_hex(b"abc"),
            "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad"
        );
    }

    #[test]
    fn test_constants() {
        assert_eq!(PROTOCOL_VERSION, 1);
        assert_eq!(MAX_PAYLOAD_SIZE, 16 * 1024 * 1024);
        assert_eq!(DEFAULT_CONTROL_PORT, 6200);
        assert_eq!(DEFAULT_PUBLIC_PORT, 6210);
        assert_eq!(HEARTBEAT_INTERVAL_SECS, 15);
        assert_eq!(HEARTBEAT_TIMEOUT_SECS, 90);
        assert_eq!(TAKEOVER_AFTER_MISSED_HEARTBEATS, 2);
        assert_eq!(SESSION_STALE_SECS, 90);
    }
}
